import { mkdirSync, writeFileSync } from 'node:fs';
import { FX_GEN } from '../src/fxsprites';
import { MOB_GEN } from '../src/sprites';
import { newGrid, packStrip, type Grid } from '../src/grid';
import { TILESETS } from '../src/tileset';
import { ART_GEN } from '../src/artsheets';
import { ATLAS_COLS, CELLS, pieces } from '../src/tilebake';
import { encodePng } from './png';
import { slug } from './slug';

/* npm run bake: run the art generators and write their output as PNG sheets
   (the game ships and loads the PNGs), plus a generated module per kind
   listing the sheets and their layout:
     skill effects (fxsprites.ts) -> assets/fx/<name>.png,   src/fxbaked.ts
     enemies (sprites.ts/mobart.ts) -> assets/mobs/<slug>.png, src/mobbaked.ts
   Re-run after changing any of that art; the smoke test fails on a sheet
   that no longer matches its generator. */


const header = '// GENERATED by scripts/bake.ts (npm run bake): do not edit.\n';
mkdirSync('assets/fx', { recursive: true });
mkdirSync('assets/mobs', { recursive: true });

/* ---- skill effects: every generator in FX_GEN ---- */
{
  const imports: string[] = [], lines: string[] = [];
  Object.keys(FX_GEN).forEach((name) => {
    const s = FX_GEN[name]();
    writeFileSync(`assets/fx/${name}.png`, encodePng(packStrip(s.frames)));
    imports.push(`import ${name} from '../assets/fx/${name}.png';`);
    lines.push(`  ${name}: { src: ${name}, w: ${s.w}, h: ${s.h}, n: ${s.frames.length}, ox: ${s.ox}, oy: ${s.oy} },`);
  });
  writeFileSync('src/fxbaked.ts', `${header}${imports.join('\n')}
import type { BakedSheet } from './fxsheets';

export const BAKED: Record<string, BakedSheet> = {
${lines.join('\n')}
};
`);
}

/* ---- enemies: every base enemy in MOB_GEN (frames, then the hurt pose) ---- */
{
  const imports: string[] = [], lines: string[] = [];
  Object.keys(MOB_GEN).forEach((name, i) => {
    const a = MOB_GEN[name]();
    writeFileSync(`assets/mobs/${slug(name)}.png`, encodePng(packStrip([...a.frames, a.hurt].map((s) => s.g))));
    imports.push(`import m${i} from '../assets/mobs/${slug(name)}.png';`);
    lines.push(`  ${JSON.stringify(name)}: { src: m${i}, w: ${a.hurt.w}, h: ${a.hurt.h}, n: ${a.frames.length}, fps: ${a.fps} },`);
  });
  writeFileSync('src/mobbaked.ts', `${header}${imports.join('\n')}
import type { BakedMob } from './sprites';

export const BAKED_MOBS: Record<string, BakedMob> = {
${lines.join('\n')}
};
`);
}

/* ---- tilesets: every piece, deduped into one atlas per piece size ---- */
{
  mkdirSync('assets/tiles', { recursive: true });
  const imports: string[] = [], lines: string[] = [];
  let n = 0;
  for (const [name, ts] of Object.entries(TILESETS)) {
    const sizes: { w: number; h: number; cells: Grid[]; seen: Map<string, number> }[] = [];
    const at = pieces(ts).map(([, paint]) => {
      const s = paint();
      if (!s) return -1;
      let k = sizes.findIndex((z) => z.w === s.w && z.h === s.h);
      if (k < 0) k = sizes.push({ w: s.w, h: s.h, cells: [], seen: new Map() }) - 1;
      const z = sizes[k], sig = Buffer.from(s.g.px).toString('base64');
      let i = z.seen.get(sig);
      if (i === undefined) { i = z.cells.push(s.g) - 1; z.seen.set(sig, i); }
      return k * CELLS + i;
    });
    const sheets = sizes.map((z, k) => {
      const file = `${slug(name)}-${z.w}x${z.h}`;
      writeFileSync(`assets/tiles/${file}.png`, encodePng(packAtlas(z.cells, z.w, z.h)));
      imports.push(`import t${n} from '../assets/tiles/${file}.png';`);
      return `{ src: t${n++}, w: ${z.w}, h: ${z.h} }`;
    });
    lines.push(`  ${JSON.stringify(name)}: { sheets: [${sheets.join(', ')}], at: [${at.join(',')}] },`);
  }
  writeFileSync('src/tilebaked.ts', `${header}${imports.join('\n')}
import type { BakedTiles } from './tilebake';

export const BAKED_TILES: Record<string, BakedTiles> = {
${lines.join('\n')}
};
`);
}

/* ---- scenery: props, town decor, backdrop layers, the portal (one PNG each) ---- */
{
  mkdirSync('assets/art', { recursive: true });
  const imports: string[] = [], lines: string[] = [];
  Object.keys(ART_GEN).forEach((key, i) => {
    writeFileSync(`assets/art/${slug(key)}.png`, encodePng(ART_GEN[key]()));
    imports.push(`import a${i} from '../assets/art/${slug(key)}.png';`);
    lines.push(`  ${JSON.stringify(key)}: a${i},`);
  });
  writeFileSync('src/artbaked.ts', `${header}${imports.join('\n')}

export const BAKED_ART: Record<string, string> = {
${lines.join('\n')}
};
`);
}

/** Cells laid out ATLAS_COLS to a row. */
function packAtlas(cells: Grid[], w: number, h: number): Grid {
  const cols = Math.min(ATLAS_COLS, cells.length), o = newGrid(cols * w, Math.ceil(cells.length / ATLAS_COLS) * h);
  cells.forEach((g, i) => {
    const x0 = (i % ATLAS_COLS) * w, y0 = Math.floor(i / ATLAS_COLS) * h;
    for (let y = 0; y < h; y++) o.px.set(g.px.subarray(y * w * 4, (y + 1) * w * 4), ((y0 + y) * o.w + x0) * 4);
  });
  return o;
}

console.log(`baked ${Object.keys(FX_GEN).length} effect, ${Object.keys(MOB_GEN).length} enemy ${Object.keys(TILESETS).length} tileset and ${Object.keys(ART_GEN).length} scenery sheet(s)`);
