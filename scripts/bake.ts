import { mkdirSync, writeFileSync } from 'node:fs';
import { FX_GEN } from '../src/fxsprites';
import { MOB_GEN } from '../src/sprites';
import { packStrip } from '../src/grid';
import { encodePng } from './png';
import { slug } from './slug';

/* npm run bake: run the art generators and write their output as PNG sheets
   (the game ships and loads the PNGs), plus a generated module per kind
   listing the sheets and their layout:
     skill effects (fxsprites.ts) -> assets/fx/<name>.png,   src/fxbaked.ts
     enemies (sprites.ts/mobart.ts) -> assets/mobs/<slug>.png, src/mobbaked.ts
   Re-run after changing any of that art; the smoke test fails on a sheet
   that no longer matches its generator. */


const header = '// GENERATED by scripts/bake.ts (npm run bake): do not edit.\n';
mkdirSync('assets/fx', { recursive: true });
mkdirSync('assets/mobs', { recursive: true });

/* ---- skill effects: every generator in FX_GEN ---- */
{
  const imports: string[] = [], lines: string[] = [];
  Object.keys(FX_GEN).forEach((name) => {
    const s = FX_GEN[name]();
    writeFileSync(`assets/fx/${name}.png`, encodePng(packStrip(s.frames)));
    imports.push(`import ${name} from '../assets/fx/${name}.png';`);
    lines.push(`  ${name}: { src: ${name}, w: ${s.w}, h: ${s.h}, n: ${s.frames.length}, ox: ${s.ox}, oy: ${s.oy} },`);
  });
  writeFileSync('src/fxbaked.ts', `${header}${imports.join('\n')}
import type { BakedSheet } from './fxsheets';

export const BAKED: Record<string, BakedSheet> = {
${lines.join('\n')}
};
`);
}

/* ---- enemies: every base enemy in MOB_GEN (frames, then the hurt pose) ---- */
{
  const imports: string[] = [], lines: string[] = [];
  Object.keys(MOB_GEN).forEach((name, i) => {
    const a = MOB_GEN[name]();
    writeFileSync(`assets/mobs/${slug(name)}.png`, encodePng(packStrip([...a.frames, a.hurt].map((s) => s.g))));
    imports.push(`import m${i} from '../assets/mobs/${slug(name)}.png';`);
    lines.push(`  ${JSON.stringify(name)}: { src: m${i}, w: ${a.hurt.w}, h: ${a.hurt.h}, n: ${a.frames.length}, fps: ${a.fps} },`);
  });
  writeFileSync('src/mobbaked.ts', `${header}${imports.join('\n')}
import type { BakedMob } from './sprites';

export const BAKED_MOBS: Record<string, BakedMob> = {
${lines.join('\n')}
};
`);
}

console.log(`baked ${Object.keys(FX_GEN).length} effect and ${Object.keys(MOB_GEN).length} enemy sheet(s)`);
