import { writeFileSync } from 'node:fs';
import { FX_GEN } from '../src/fxsprites';
import { packStrip } from '../src/grid';
import { encodePng } from './png';

/* npm run bake: run each effect's generator (fxsprites.ts) and write it as
   a PNG sheet in assets/fx, plus src/fxbaked.ts listing the sheets and their
   layout for the game to load. Re-run after changing an effect; the tests
   fail on a sheet that no longer matches its generator. */

/** The effects that ship as baked sheets (the rest still run their generator). */
export const BAKE: string[] = ['flurry'];

const lines: string[] = [];
const imports: string[] = [];
for (const name of BAKE) {
  const s = FX_GEN[name]();
  writeFileSync(`assets/fx/${name}.png`, encodePng(packStrip(s.frames)));
  imports.push(`import ${name} from '../assets/fx/${name}.png';`);
  lines.push(`  ${name}: { src: ${name}, w: ${s.w}, h: ${s.h}, n: ${s.frames.length}, ox: ${s.ox}, oy: ${s.oy} },`);
}
writeFileSync('src/fxbaked.ts', `// GENERATED by scripts/bakefx.ts (npm run bake): do not edit.
${imports.join('\n')}
import type { BakedSheet } from './fxsheets';

export const BAKED: Record<string, BakedSheet> = {
${lines.join('\n')}
};
`);
console.log(`baked ${BAKE.length} effect sheet(s) to assets/fx`);
